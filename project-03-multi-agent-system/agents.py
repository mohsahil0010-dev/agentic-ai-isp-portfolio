SPECIALIST_AGENTS = {
    "fiber_agent": fiber_agent,
    "network_agent": network_agent,
    "billing_agent": billing_agent,
}


def run_assigned_specialist(
    agent_name: str,
    incident: IncidentInput,
) -> SpecialistFinding:
    """Run one specialist selected by the coordinator."""

    agent_function = SPECIALIST_AGENTS.get(agent_name)

    if agent_function is None:
        raise ValueError(
            f"Unknown specialist agent: {agent_name}"
        )

    return agent_function(incident)


def deterministic_final_draft(
    findings: list[SpecialistFinding],
) -> FinalDecisionDraft:
    """Create a reliable final decision without requiring the API."""

    fault_summaries: list[str] = []
    action_plan: list[str] = []
    teams: list[str] = []

    team_names = {
        "fiber_agent": "Fiber Team",
        "network_agent": "Network Team",
        "billing_agent": "Billing Team",
    }

    for finding in findings:
        if finding.tool_observations:
            observation = finding.tool_observations[0]

            if observation.status in {"fault", "warning"}:
                fault_summaries.append(observation.summary)

        action_plan.extend(finding.recommended_actions)

        team_name = team_names.get(finding.agent)

        if team_name:
            teams.append(team_name)

    action_plan = unique_items(action_plan)
    teams = unique_items(teams)

    if fault_summaries:
        probable_root_cause = " ".join(
            unique_items(fault_summaries)
        )
        decision = (
            "The incident requires coordinated specialist action. "
            "Complete the verified checks in order and restore service "
            "only after the physical, network and billing conditions "
            "are confirmed."
        )
    else:
        probable_root_cause = (
            "No confirmed fault was established from the supplied "
            "incident evidence."
        )
        decision = (
            "Collect the missing diagnostic information before making "
            "a service-impacting change."
        )

    if not action_plan:
        action_plan = [
            "Collect additional fiber, PPPoE and billing evidence.",
        ]

    confidence_values = {
        finding.confidence
        for finding in findings
    }

    if "high" in confidence_values:
        confidence = "high"
    elif "medium" in confidence_values:
        confidence = "medium"
    else:
        confidence = "low"

    return FinalDecisionDraft(
        probable_root_cause=probable_root_cause,
        decision=decision,
        action_plan=action_plan,
        assigned_team=", ".join(teams) or "Support Team",
        confidence=confidence,
    )


def final_decision_agent(
    incident: IncidentInput,
    triage: TriageDecision,
    findings: list[SpecialistFinding],
) -> FinalIncidentReport:
    """Combine all findings using the LLM with a safe fallback."""

    findings_json = json.dumps(
        [
            finding.model_dump()
            for finding in findings
        ],
        indent=2,
    )

    system_prompt = """
You are the final decision agent in a fictional ISP multi-agent
incident response system.

Combine the coordinator triage and specialist findings into one clear
operational decision.

Rules:

1. Use only the supplied evidence.
2. Do not invent completed tests, payments or repairs.
3. Prioritize direct diagnostic-tool evidence.
4. Put urgent and safety-related actions first.
5. Do not expose private credentials.
6. Account restoration requires approved billing verification.
7. Return a concise ordered action plan.
""".strip()

    try:
        structured_llm = get_llm().with_structured_output(
            FinalDecisionDraft,
            method="json_schema",
        )

        draft = structured_llm.invoke(
            [
                SystemMessage(content=system_prompt),
                HumanMessage(
                    content=(
                        "Incident:\n\n"
                        f"{format_incident(incident)}\n\n"
                        "Coordinator triage:\n\n"
                        f"{triage.model_dump_json(indent=2)}\n\n"
                        "Specialist findings:\n\n"
                        f"{findings_json}"
                    )
                ),
            ]
        )

        confidence = draft.confidence.lower()

        if confidence not in {"high", "medium", "low"}:
            confidence = "medium"

    except Exception:
        draft = deterministic_final_draft(findings)
        confidence = draft.confidence

    requires_escalation = (
        triage.requires_human_escalation
        or any(
            finding.requires_escalation
            for finding in findings
        )
    )

    return FinalIncidentReport(
        incident_id=incident.incident_id,
        category=triage.category,
        priority=triage.priority,
        probable_root_cause=draft.probable_root_cause,
        decision=draft.decision,
        action_plan=draft.action_plan,
        assigned_team=draft.assigned_team,
        confidence=confidence,
        requires_human_escalation=requires_escalation,
        specialist_findings=findings,
        workflow_path=[],
    )