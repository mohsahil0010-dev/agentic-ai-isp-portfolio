DEFAULT_MODEL = "openai/gpt-oss-20b"


class FinalDecisionDraft(BaseModel):
    """Small structured response generated by the final LLM."""

    probable_root_cause: str
    decision: str
    action_plan: list[str]
    assigned_team: str
    confidence: str


def get_llm() -> ChatGroq:
    """Create the Groq language model used by the agents."""

    if not os.getenv("GROQ_API_KEY"):
        raise RuntimeError(
            "GROQ_API_KEY is missing. Add it to the local .env file."
        )

    model_name = os.getenv("GROQ_MODEL", DEFAULT_MODEL)

    return ChatGroq(
        model=model_name,
        temperature=0,
        timeout=90,
        max_retries=5,
    )


def format_incident(incident: IncidentInput) -> str:
    """Convert an incident into formatted JSON."""

    return incident.model_dump_json(indent=2)


def unique_items(items: list[str]) -> list[str]:
    """Remove duplicate strings while preserving their order."""

    return list(dict.fromkeys(item for item in items if item))


def deterministic_triage(
    incident: IncidentInput,
) -> TriageDecision:
    """Create a safe triage result without requiring the API."""

    description = incident.description.lower()
    assigned_agents: list[str] = []
    reasons: list[str] = []

    fiber_keywords = (
        "fiber",
        "los",
        "pon",
        "onu",
        "optical",
        "signal",
        "splice",
        "connector",
    )

    network_keywords = (
        "pppoe",
        "mikrotik",
        "router",
        "internet",
        "network",
        "wan",
        "dns",
        "offline",
    )

    billing_keywords = (
        "payment",
        "paid",
        "unpaid",
        "billing",
        "balance",
        "account",
        "disabled",
    )

    fiber_evidence = (
        incident.onu_los_status == "red"
        or incident.onu_pon_status == "offline"
        or incident.rx_power_dbm is not None
        or any(word in description for word in fiber_keywords)
    )

    network_evidence = (
        incident.pppoe_status != "unknown"
        or any(word in description for word in network_keywords)
    )

    billing_evidence = (
        incident.payment_status != "unknown"
        or incident.account_status != "unknown"
        or any(word in description for word in billing_keywords)
    )

    if fiber_evidence:
        assigned_agents.append("fiber_agent")
        reasons.append(
            "The incident contains ONU, LOS, PON, optical-signal "
            "or fiber evidence."
        )

    if network_evidence:
        assigned_agents.append("network_agent")
        reasons.append(
            "The incident contains PPPoE, router or network evidence."
        )

    if billing_evidence:
        assigned_agents.append("billing_agent")
        reasons.append(
            "The incident contains payment or account-status evidence."
        )

    if len(assigned_agents) > 1:
        category = "mixed"
    elif assigned_agents == ["fiber_agent"]:
        category = "fiber"
    elif assigned_agents == ["network_agent"]:
        category = "network"
    elif assigned_agents == ["billing_agent"]:
        category = "billing"
    else:
        category = "unknown"

    broad_outage = any(
        phrase in description
        for phrase in (
            "all customers",
            "all users",
            "multiple customers",
            "multiple users",
            "area outage",
            "complete outage",
        )
    )

    critical_optical_signal = (
        incident.rx_power_dbm is not None
        and incident.rx_power_dbm < -27
    )

    if broad_outage:
        priority = "critical"
    elif (
        incident.onu_los_status == "red"
        or critical_optical_signal
    ):
        priority = "high"
    elif (
        incident.pppoe_status == "inactive"
        or incident.account_status == "disabled"
        or incident.payment_status in {"unpaid", "partial"}
    ):
        priority = "medium"
    else:
        priority = "low"

    return TriageDecision(
        category=category,
        priority=priority,
        assigned_agents=assigned_agents,
        reason=" ".join(reasons) or (
            "The supplied incident does not contain enough evidence "
            "to select a specialist."
        ),
        requires_human_escalation=broad_outage,
    )


def coordinator_agent(
    incident: IncidentInput,
) -> TriageDecision:
    """Use the LLM for triage with a deterministic fallback."""

    system_prompt = """
You are the coordinator of a fictional ISP multi-agent incident
response system.

Analyze the submitted incident and assign all relevant specialists.

Available specialists:

- fiber_agent: ONU, LOS, PON, RX power, fiber and optical faults
- network_agent: PPPoE, MikroTik, router, WAN and service faults
- billing_agent: payments, balances, account enablement and suspension

Rules:

1. Assign every specialist needed for a reliable diagnosis.
2. Use category "mixed" when multiple areas are involved.
3. A red LOS or critical optical signal is high priority.
4. A broad outage or safety risk is critical priority.
5. A paid-but-disabled account requires billing investigation.
6. Use only the supplied fictional incident data.
""".strip()

    try:
        structured_llm = get_llm().with_structured_output(
            TriageDecision,
            method="json_schema",
        )

        return structured_llm.invoke(
            [
                SystemMessage(content=system_prompt),
                HumanMessage(
                    content=(
                        "Triage this fictional ISP incident:\n\n"
                        f"{format_incident(incident)}"
                    )
                ),
            ]
        )
    except Exception:
        return deterministic_triage(incident)


def fiber_agent(
    incident: IncidentInput,
) -> SpecialistFinding:
    """Run the optical diagnostic tool and return its finding."""

    observation_data = check_optical_signal.invoke(
        {
            "onu_pon_status": incident.onu_pon_status,
            "onu_los_status": incident.onu_los_status,
            "rx_power_dbm": incident.rx_power_dbm,
        }
    )

    observation = ToolObservation(**observation_data)

    evidence = [
        f"ONU PON status: {incident.onu_pon_status}",
        f"ONU LOS status: {incident.onu_los_status}",
        f"Tool status: {observation.status}",
    ]

    if incident.rx_power_dbm is not None:
        evidence.append(
            f"RX optical power: {incident.rx_power_dbm:.1f} dBm"
        )

    recommended_actions = [
        observation.recommended_check,
        "Record the result of every physical fiber and optical test.",
    ]

    if observation.status == "fault":
        diagnosis = observation.summary
        confidence = "high"
        requires_escalation = True
    elif observation.status == "warning":
        diagnosis = observation.summary
        confidence = "medium"
        requires_escalation = True
    elif observation.status == "normal":
        diagnosis = (
            "The supplied optical evidence does not show a confirmed "
            "fiber fault."
        )
        confidence = "high"
        requires_escalation = False
    else:
        diagnosis = (
            "The optical condition cannot be confirmed from the "
            "supplied information."
        )
        confidence = "low"
        requires_escalation = False

    return SpecialistFinding(
        agent="fiber_agent",
        diagnosis=diagnosis,
        evidence=evidence,
        recommended_actions=recommended_actions,
        confidence=confidence,
        requires_escalation=requires_escalation,
        tool_observations=[observation],
    )


